/** Every GitHub call Slade can surface as an in-chat activity card. */
export type GitHubActionKind =
  | 'get-file'
  | 'create-file'
  | 'update-file'
  | 'delete-file'
  | 'get-blob'
  | 'create-blob'
  | 'get-tree'
  | 'create-tree'
  | 'create-branch'
  | 'delete-branch'
  | 'get-branch'
  | 'list-branches'
  | 'update-ref'
  | 'get-commit'
  | 'create-commit'
  | 'create-pr'
  | 'merge-pr'
  | 'get-pr'
  | 'list-prs'
  | 'create-issue'
  | 'list-issues'
  | 'create-gist'
  | 'list-gists'
  | 'search-code'
  | 'search-repos'
  | 'list-repos'
  | 'get-repo'
  | 'clone-repo'
  | 'test-token'
  | 'rate-limit'
  | 'sign-in'
  | 'sign-out'
  | 'other'

export interface GitHubActionInfo {
  kind: GitHubActionKind
  /** Card title, already prefixed. */
  title: string
  /** The path, branch, query, or repo the call touched. */
  subject: string
  repo?: string
  ref?: string
}

export type GitHubActionStatus = 'running' | 'done' | 'error' | 'cancelled'

/** Persistable, read-only content for one GitHub action card. */
export interface GitHubActionArtifact extends GitHubActionInfo {
  id: string
  status: GitHubActionStatus
  at: number
  elapsedMs?: number
  error?: string
  /** How many identical calls this card stands for. */
  count: number
}

export type ArtifactKind =
  | 'image'
  | 'code'
  | 'doc'
  | 'sheet'
  | 'audio'
  | 'video'
  | 'archive'
  | 'unknown'

export type ArtifactSource = { origin: 'user' } | { origin: 'model'; modelId: string; modelLabel: string }

/** Where a file came from when it was not uploaded from disk (GitHub repos). */
export interface RemoteSource {
  kind: 'github'
  /** `owner/name`. */
  repo: string
  /** Branch, tag or commit sha the file was read at. */
  ref: string
  path: string
  /** Canonical permalink on github.com. */
  url: string
  sha?: string
}

export interface Artifact {
  id: string
  name: string
  mime: string
  size: number
  kind: ArtifactKind
  createdAt: number
  provenance: ArtifactSource
  /** Set when the artifact was pulled from a repository rather than uploaded. */
  remote?: RemoteSource
  /** Set when the artifact is backed by a file in the local file system. */
  localPath?: string
  /** Small artifacts are persisted as data URLs; larger ones live in memory. */
  dataURL?: string
  /** Runtime object URL (never persisted; recreated from dataURL on load). */
  blobUrl?: string
  /** Text preview for code / docs / sheets. */
  text?: string
  /** Parsed CSV columns/rows for sheet preview. */
  columns?: string[]
  rows?: string[][]
  /** Media duration in seconds when known. */
  durationSec?: number
  /** True when the artifact exists only for this session (large files). */
  ephemeral?: boolean
}

