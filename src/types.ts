export interface DefaultsSettings {
  temperature: number
  topP: number
  maxTokens: number
  systemPrompt: string
  stream: boolean
  typingIndicator: boolean
  /** Whether to show model thinking / reasoning by default. */
  showThoughts?: boolean
  autoScroll: 'smooth' | 'instant' | 'off'
  failoverStrategy: FailoverStrategy
  /** Max gap between streamed chunks before the stream is declared stalled. */
  requestTimeoutMs: number
  /** How long to wait for the *first* token. Reasoning models need more. */
  firstTokenTimeoutMs: number
}

export interface ArtifactSettings {
  collapsedByDefault: boolean
  autoExpandImages: boolean
  maxPreviewHeight: number
}

/** Orchestrator agent configuration (Settings → Agent). */
export interface AgentSettings {
  /** Model that plans, delegates and synthesizes. Undefined = top of the chain. */
  orchestratorModelId?: string
  /** Upper bound on subtasks per run. */
  maxSteps: number
  /** How many workers may run at once (1 = strictly sequential). */
  maxParallel: number
  /** When false the plan card collapses worker outputs to one line each. */
  expandStepResults: boolean
  /**
   * Output token ceiling for the orchestrator's own calls (plan, each worker
   * step, synthesis). Deliberately well above the chat default: a step is a
   * whole deliverable ("build the app"), and reasoning models bill their
   * thinking against the same cap — a 4k ceiling is how a step comes back
   * empty. Raising a ceiling costs nothing unless the tokens are used.
   */
  stepMaxTokens: number
  /**
   * When true, agents automatically read existing files from the local file
   * system as workspace context and store emitted files back into it.
   */
  useLocalFs: boolean
}

export interface AppearanceSettings {
  theme: ThemePref
  fontSize: number
  density: Density
  codeTheme: 'auto' | 'light' | 'dark'
  reduceMotion: boolean
  enterToSend: boolean
}

/**
 * An individual API token/key configured under a provider connection.
 * Multiple tokens can be pooled for automatic load balancing and failover
 * when rate limits (429) or quota errors (402) occur.
 */
export interface ApiTokenDef {
  /** Unique token identifier. */
  id: string
  /** The secret API key string. */
  key: string
  /** Optional human label, e.g. "Primary", "Personal Tier", "Backup". */
  label?: string
  /** Whether this token is active in the candidate pool (default true). */
  enabled?: boolean
  /** Timestamp when added. */
  createdAt?: number
}

/**
 * One configured provider connection. Slade ships with one instance per
 * supported kind, and more can be added (Settings → Providers) — several
 * OpenAI-compatible endpoints (Groq, DeepSeek, Ollama…) or a second account
 * on the same provider each get their own entry, key and models.
 */
export interface ProviderDef {
  /** Unique instance id. Factory instances reuse their kind as id. */
  id: string
  /** Which wire protocol/adapter this connection speaks. */
  kind: ProviderId
  /** Display name, e.g. "OpenAI" or "Groq". Editable. */
  label: string
  /** Primary / default API key (kept in sync with apiKeys[0]). */
  apiKey: string
  /** Pool of API tokens for rotation and independent cooldown tracking. */
  apiKeys?: ApiTokenDef[]
  /** Default endpoint override for kinds that support it (openai-compatible). */
  baseURL?: string
}

export interface Settings {
  version: 1
  models: ModelDef[]
  defaults: DefaultsSettings
  artifacts: ArtifactSettings
  appearance: AppearanceSettings
  agent: AgentSettings
  providers: ProviderDef[]
  pinnedModelId?: string
}

