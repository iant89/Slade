/* Orchestrator agent (agent mode)                                     */
/* ------------------------------------------------------------------ */

export type AgentPhase =
  | 'planning'
  | 'executing'
  | 'synthesizing'
  | 'complete'
  | 'error'
  /**
   * The orchestrator stopped before delegating to ask the user something. The
   * turn is finished (nothing is in flight) and the run resumes in place as
   * soon as the last question has been answered.
   */
  | 'awaiting_input'

export type AgentStepStatus = 'pending' | 'running' | 'complete' | 'error' | 'skipped'

/* ------------------------------------------------------------------ */
/* Clarification questions (agent asks, user chooses)                  */
/* ------------------------------------------------------------------ */

/** One selectable choice in a question the agent asked. */
export interface AgentQuestionOption {
  id: string
  label: string
  /** Optional one-line explanation of what picking this option means. */
  hint?: string
}

/** What the user chose. Stored so the answer survives any later re-render. */
export interface AgentQuestionAnswer {
  /** Ids of the predefined options that were picked (empty for a typed answer). */
  optionIds: string[]
  /** Labels resolved at answer time, so the record outlives the option list. */
  labels: string[]
  /** The free-text answer, when the user typed their own instead of choosing. */
  custom?: string
  /** Canonical one-line answer, exactly as it is handed back to the model. */
  text: string
}

export type AgentQuestionStatus = 'pending' | 'answered' | 'skipped'

/**
 * One multi-choice question the orchestrator asked before it could plan.
 * Questions are answered one at a time: an answered question collapses into a
 * read-only answer card and the next pending one is revealed underneath it.
 */
export interface AgentQuestion {
  id: string
  /** The question itself. */
  prompt: string
  /** Optional context: why the agent needs to know. */
  detail?: string
  options: AgentQuestionOption[]
  /**
   * Whether the user may type their own answer instead of picking an option.
   * Almost always true — a choice list that cannot be contradicted is a trap.
   */
  allowCustom: boolean
  /**
   * Hint for the free-text field, used both under the "type your own answer"
   * option and as the field's placeholder, e.g. `e.g. "Q2 vs Q2 last year"`.
   */
  customLabel?: string
  /** True when more than one option may be selected. */
  multiple?: boolean
  status: AgentQuestionStatus
  answer?: AgentQuestionAnswer
  /** Why the question was skipped, when it wasn't the user's own choice. */
  note?: string
  askedAt: number
  answeredAt?: number
  /** Model that asked, for attribution on the card. */
  modelId?: string
}

/** One card in the agent's chronological output: a thought segment or GitHub call. */
export type AgentTimelineItem =
  | {
      id: string
      type: 'thought'
      /** Planning, synthesis, or the id of the worker step that produced it. */
      sourceId: string
      modelId: string
      text: string
      /** True only while this contiguous thought segment is being streamed. */
      streaming?: boolean
    }
  | {
      id: string
      type: 'github'
      card: GitHubActionArtifact
    }

/**
 * One subtask the orchestrator delegated to a worker model. Persisted with
 * the message so the whole run stays inspectable after a reload.
 */
export interface AgentStep {
  id: string
  title: string
  /** Full self-contained prompt the worker received. */
  prompt: string
  modelId: string
  /** Resolved at plan time; kept separately so a renamed model still renders. */
  modelLabel: string
  status: AgentStepStatus
  /** The worker's full output. */
  result?: string
  /** Internal thinking / reasoning text generated by the worker model. */
  reasoning?: string
  error?: string
  /** Failures inside this step's own failover walk, tried order. */
  attempts: AttemptFailure[]
  /** Worker model ids that failed before this step produced output. */
  failedChain: string[]
  elapsedMs?: number
  /** True when the worker's output was cut off by the token cap. */
  truncated?: boolean
  /** Files created, updated, moved, or deleted in the local file system by this step. */
  fsOps?: FsOpRecord[]
}

export interface AgentRun {
  phase: AgentPhase
  /** The user's goal this run is executing. */
  goal: string
  orchestratorModelId: string
  steps: AgentStep[]
  /** Orchestrator's internal thinking / reasoning during planning. */
  planningReasoning?: string
  /** Orchestrator's one-line strategy note from the planning call. */
  strategy?: string
  /** Set when planning had to fall back (unparseable plan → single step). */
  note?: string
  error?: string
  startedAt: number
  finishedAt?: number
  /** Aggregate local file system operations performed across this run. */
  fsOps?: FsOpRecord[]
  /**
   * Thought and GitHub cards in the exact order they were emitted. Thought
   * segments split around GitHub calls, so a live call appears between the
   * thought card that was open and the next thought card.
   */
  timeline?: AgentTimelineItem[]
  /**
   * Identifies the GitHub cards this run produced, so they render inside the
   * run's answer rather than in the chat panel.
   */
  githubScope?: string
  /**
   * Clarification questions the orchestrator asked, in the order they were
   * asked. Answered ones keep their chosen answer, so the whole exchange stays
   * inspectable after the run continues (and after a reload).
   */
  questions?: AgentQuestion[]
  /** How many ask-rounds this run has already used (capped, see `lib/questions`). */
  questionRounds?: number
  /**
   * Where the project's roadmap / milestone file stands after this run:
   * previous, current and next step plus overall progress. Present only when
   * a roadmap was actually used (see `src/lib/roadmap.ts`).
   */
  roadmap?: RoadmapReport
}

/* ------------------------------------------------------------------ */
/* Roadmap tracking (orchestrator completion report)                   */
/* ------------------------------------------------------------------ */

export type RoadmapStatus = 'done' | 'active' | 'todo'

/** One roadmap step as it appears on the completion timeline. */
export interface RoadmapTimelineStep {
  /** 1-based position among all of the roadmap's steps. */
  index: number
  label: string
  status: RoadmapStatus
  /** Enclosing milestone / section heading, when the roadmap has one. */
  group?: string
  /** True when this step's status changed during the run. */
  changed?: boolean
}

/** A step whose status moved during the run (or that was added / removed). */
export interface RoadmapChange {
  label: string
  from: RoadmapStatus | 'new'
  to: RoadmapStatus | 'removed'
}

export interface RoadmapProgress {
  done: number
  active: number
  total: number
  /** Whole-number completion, `round(done / total * 100)`. */
  percent: number
}

/**
 * The completion timeline Slade shows under an orchestrated run's final
 * answer. Derived by diffing the roadmap file before and after the run — never
 * from a model's own claim about it — and persisted with the message.
 */
export interface RoadmapReport {
  /** Local file system path of the roadmap that was used, e.g. `ROADMAP.md`. */
  path: string
  title?: string
  previous?: RoadmapTimelineStep
  current?: RoadmapTimelineStep
  next?: RoadmapTimelineStep
  /** Overall completion after the run. */
  progress: RoadmapProgress
  /** Completion when the run started; absent when the roadmap was created by the run. */
  before?: RoadmapProgress
  /** Status transitions this run made to the roadmap, in roadmap order. */
  changes: RoadmapChange[]
}

